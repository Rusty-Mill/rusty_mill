/// The body name for a loadout `body` product id, if known.
pub fn car_name(body_id: u32) -> Option<&'static str> {
    CAR_BODIES
        .binary_search_by_key(&body_id, |&(id, _)| id)
        .ok()
        .map(|i| CAR_BODIES[i].1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_bodies_resolve_and_table_is_sorted() {
        // Anchors verified against ballchasing's own `car_name`.
        assert_eq!(car_name(23), Some("Octane"));
        assert_eq!(car_name(31), Some("Venom"));
        assert_eq!(car_name(403), Some("Dominus"));
        assert_eq!(car_name(1172), Some("Marauder"));
        assert_eq!(car_name(4284), Some("Fennec"));
        assert_eq!(car_name(999999), None);
        assert!(
            CAR_BODIES.windows(2).all(|w| w[0].0 < w[1].0),
            "ids sorted & unique"
        );
    }
}
